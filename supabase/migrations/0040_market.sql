-- =====================================================================
-- 0040 — TIR Bazarı (truck / trailer / machinery sale ads)
--
-- * market_listings: one sale ad. Owner writes draft / submits it
--   ("Elanı dərc et" → pending); an ADMIN approves it (active) before
--   anybody else sees it. Owner can edit, mark sold, delete their own ad.
--   Editing an active ad sends it back to the admin (pending).
--   Moderation / VIP / views columns are protected by a trigger: only
--   admins (and the trusted server functions below) change them.
-- * market_favorites: "Seçilmişlər" (own rows only).
-- * market_views + market_record_view(): real view counter, one per
--   viewer per day, the owner's own views not counted.
-- * market_search() / market_similar(): feed with filters (VIP first),
--   similar ads (same brand + model, then same brand; VIP first).
-- * admin_market_set_status / admin_market_set_vip / admin_market_delete:
--   moderation, VIP on / off with an end date (ready for paid VIP later,
--   no payment now). Every admin action is logged (_admin_log).
-- * reports: + target 'market_listing' (existing values all kept).
-- * storage bucket market-photos (public read, owner folder = user id).
--
-- Safe: forward-only, re-runnable. Only NEW tables / functions /
-- policies; the reports check keeps every value it already allowed.
-- No existing row is changed or deleted.
-- =====================================================================

create table if not exists public.market_listings (
  id uuid primary key default gen_random_uuid(),
  listing_no bigint generated by default as identity (start with 10001) unique,
  owner_id uuid not null references public.users(id) on delete cascade,
  status text not null default 'draft'
    check (status in ('draft','pending','active','rejected','inactive','sold')),
  category text not null default 'truck'
    check (category in ('truck','trailer','semitrailer','construction','other')),
  brand text check (brand is null or char_length(brand) <= 60),
  model text check (model is null or char_length(model) <= 60),
  year integer check (year is null or year between 1950 and 2100),
  mileage_km integer check (mileage_km is null or mileage_km between 0 and 10000000),
  engine_l numeric(4,1) check (engine_l is null or engine_l between 0 and 99),
  power_hp integer check (power_hp is null or power_hp between 0 and 5000),
  gearbox text check (gearbox is null or gearbox in ('manual','automatic','semi')),
  fuel text check (fuel is null or fuel in ('diesel','petrol','gas','electric','hybrid')),
  price numeric(12,2) check (price is null or price >= 0),
  currency text not null default 'USD' check (char_length(currency) between 3 and 4),
  country text check (country is null or char_length(country) <= 60),
  city text check (city is null or char_length(city) <= 80),
  lat double precision check (lat is null or lat between -90 and 90),
  lng double precision check (lng is null or lng between -180 and 180),
  phone text check (phone is null or char_length(phone) <= 30),
  description text check (description is null or char_length(description) <= 1000),
  photos text[] not null default '{}' check (cardinality(photos) <= 20),
  views integer not null default 0,
  is_vip boolean not null default false,
  vip_until timestamptz,
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  sold_at timestamptz
);
create index if not exists idx_market_status_pub on public.market_listings (status, published_at desc);
create index if not exists idx_market_owner on public.market_listings (owner_id);
create index if not exists idx_market_brand on public.market_listings (lower(brand), lower(model));

create table if not exists public.market_favorites (
  user_id uuid not null references public.users(id) on delete cascade,
  listing_id uuid not null references public.market_listings(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, listing_id)
);

create table if not exists public.market_views (
  listing_id uuid not null references public.market_listings(id) on delete cascade,
  viewer_id uuid not null references public.users(id) on delete cascade,
  day date not null default current_date,
  primary key (listing_id, viewer_id, day)
);

-- ---------------------------------------------------------------------
-- Owner rules (admins and the trusted functions below skip them).
-- ---------------------------------------------------------------------
create or replace function public.market_listing_guard()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null or public.is_admin() or current_setting('app.market_trusted', true) = '1' then
    new.updated_at := now();
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.owner_id := auth.uid();
    if new.status not in ('draft', 'pending') then new.status := 'draft'; end if;
    new.is_vip := false;
    new.vip_until := null;
    new.views := 0;
    new.admin_note := null;
    new.published_at := null;
    new.sold_at := null;
    new.created_at := now();
    new.updated_at := now();
    return new;
  end if;

  -- UPDATE by the owner: moderation, VIP and counters stay as they are.
  new.id := old.id;
  new.listing_no := old.listing_no;
  new.owner_id := old.owner_id;
  new.is_vip := old.is_vip;
  new.vip_until := old.vip_until;
  new.views := old.views;
  new.admin_note := old.admin_note;
  new.created_at := old.created_at;
  new.published_at := old.published_at;
  new.sold_at := old.sold_at;

  if new.status is distinct from old.status then
    if not (
         (new.status = 'pending' and old.status in ('draft', 'rejected', 'inactive'))
      or (new.status = 'draft' and old.status in ('pending', 'rejected'))
      or (new.status = 'sold' and old.status = 'active')
    ) then
      raise exception 'invalid_status_change' using errcode = '22023';
    end if;
  end if;

  -- Editing a published ad sends it back to the admin.
  if old.status = 'active' and new.status = 'active' and (
       new.category, new.brand, new.model, new.year, new.mileage_km, new.engine_l, new.power_hp,
       new.gearbox, new.fuel, new.price, new.currency, new.country, new.city, new.lat, new.lng,
       new.phone, new.description, new.photos)
     is distinct from (
       old.category, old.brand, old.model, old.year, old.mileage_km, old.engine_l, old.power_hp,
       old.gearbox, old.fuel, old.price, old.currency, old.country, old.city, old.lat, old.lng,
       old.phone, old.description, old.photos) then
    new.status := 'pending';
  end if;

  if new.status = 'sold' and old.status is distinct from 'sold' then new.sold_at := now(); end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists market_listing_guard on public.market_listings;
create trigger market_listing_guard
  before insert or update on public.market_listings
  for each row execute function public.market_listing_guard();

