-- ---------------------------------------------------------------------
-- Feed / search: active ads, VIP (not expired) first, newest first.
-- Runs with the caller's rights (RLS applies).
-- ---------------------------------------------------------------------
create or replace function public.market_vip_active(p_is_vip boolean, p_until timestamptz)
returns boolean language sql stable set search_path = public, pg_temp as $$
  select coalesce(p_is_vip, false) and (p_until is null or p_until > now());
$$;

create or replace function public.market_search(
  p_category text default null,
  p_q text default null,
  p_brand text default null,
  p_model text default null,
  p_city text default null,
  p_min_price numeric default null,
  p_max_price numeric default null,
  p_year_from integer default null,
  p_year_to integer default null,
  p_max_mileage integer default null,
  p_vip_only boolean default false,
  p_limit integer default 20,
  p_offset integer default 0
) returns setof public.market_listings
language sql stable security invoker set search_path = public, pg_temp as $$
  select l.* from public.market_listings l
  where l.status = 'active'
    and (p_category is null or l.category = p_category)
    and (p_brand is null or lower(l.brand) = lower(p_brand))
    and (p_model is null or lower(l.model) = lower(p_model))
    and (p_city is null or l.city ilike '%' || p_city || '%')
    and (p_min_price is null or l.price >= p_min_price)
    and (p_max_price is null or l.price <= p_max_price)
    and (p_year_from is null or l.year >= p_year_from)
    and (p_year_to is null or l.year <= p_year_to)
    and (p_max_mileage is null or l.mileage_km <= p_max_mileage)
    and (not coalesce(p_vip_only, false) or public.market_vip_active(l.is_vip, l.vip_until))
    and (nullif(btrim(coalesce(p_q, '')), '') is null
         or l.brand ilike '%' || btrim(p_q) || '%'
         or l.model ilike '%' || btrim(p_q) || '%'
         or l.city ilike '%' || btrim(p_q) || '%'
         or (l.brand || ' ' || coalesce(l.model, '')) ilike '%' || btrim(p_q) || '%')
  order by public.market_vip_active(l.is_vip, l.vip_until) desc, l.published_at desc nulls last, l.created_at desc
  limit greatest(1, least(coalesce(p_limit, 20), 60))
  offset greatest(0, coalesce(p_offset, 0));
$$;

-- Similar ads: same category; same brand + model first, then the same
-- brand's other models; inside each group VIP first, then newest.
create or replace function public.market_similar(p_id uuid, p_limit integer default 10)
returns setof public.market_listings
language sql stable security invoker set search_path = public, pg_temp as $$
  with me as (select category, lower(brand) b, lower(model) m from public.market_listings where id = p_id)
  select l.* from public.market_listings l, me
  where l.status = 'active' and l.id <> p_id
    and l.category = me.category and me.b is not null and lower(l.brand) = me.b
  order by (lower(l.model) is not distinct from me.m) desc,
           public.market_vip_active(l.is_vip, l.vip_until) desc,
           l.published_at desc nulls last
  limit greatest(1, least(coalesce(p_limit, 10), 30));
$$;

-- Real view counter: one per viewer per day; the owner is not counted.
create or replace function public.market_record_view(p_id uuid)
returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare v_owner uuid; v_status text; v_views integer;
begin
  select owner_id, status, views into v_owner, v_status, v_views from public.market_listings where id = p_id;
  if v_owner is null then return null; end if;
  if auth.uid() is null or auth.uid() = v_owner or v_status <> 'active' then return v_views; end if;
  insert into public.market_views (listing_id, viewer_id) values (p_id, auth.uid()) on conflict do nothing;
  if found then
    perform set_config('app.market_trusted', '1', true);
    update public.market_listings set views = views + 1 where id = p_id returning views into v_views;
    perform set_config('app.market_trusted', '', true);
  end if;
  return v_views;
end;
$$;

-- ---------------------------------------------------------------------
-- Admin
-- ---------------------------------------------------------------------
create or replace function public.admin_market_set_status(p_id uuid, p_status text, p_note text default null)
returns public.market_listings language plpgsql security definer set search_path = public, pg_temp as $$
declare v_old public.market_listings; v_new public.market_listings;
begin
  perform public._require_admin();
  if p_status not in ('active', 'rejected', 'inactive', 'pending') then
    raise exception 'invalid_status' using errcode = '22023';
  end if;
  select * into v_old from public.market_listings where id = p_id;
  if v_old.id is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  update public.market_listings
     set status = p_status,
         admin_note = case when p_status in ('rejected', 'inactive') then nullif(btrim(coalesce(p_note, '')), '') else null end,
         published_at = case when p_status = 'active' then coalesce(published_at, now()) else published_at end
   where id = p_id returning * into v_new;
  perform public._admin_log('market.' || p_status, 'market_listing', p_id::text,
    jsonb_build_object('status', v_old.status), jsonb_build_object('status', p_status, 'note', p_note));
  return v_new;
end;
$$;

-- VIP on for p_days (null = no end date) / off. Ready for paid VIP later.
create or replace function public.admin_market_set_vip(p_id uuid, p_vip boolean, p_days integer default null)
returns public.market_listings language plpgsql security definer set search_path = public, pg_temp as $$
declare v_old public.market_listings; v_new public.market_listings;
begin
  perform public._require_admin();
  if p_days is not null and (p_days < 1 or p_days > 3650) then raise exception 'invalid_days' using errcode = '22023'; end if;
  select * into v_old from public.market_listings where id = p_id;
  if v_old.id is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  update public.market_listings
     set is_vip = coalesce(p_vip, false),
         vip_until = case when coalesce(p_vip, false) and p_days is not null then now() + make_interval(days => p_days) else null end
   where id = p_id returning * into v_new;
  perform public._admin_log(case when coalesce(p_vip, false) then 'market.vip_on' else 'market.vip_off' end, 'market_listing', p_id::text,
    jsonb_build_object('is_vip', v_old.is_vip, 'vip_until', v_old.vip_until),
    jsonb_build_object('is_vip', v_new.is_vip, 'vip_until', v_new.vip_until));
  return v_new;
end;
$$;

create or replace function public.admin_market_delete(p_id uuid, p_reason text default null)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare v_old public.market_listings;
begin
  perform public._require_admin();
  select * into v_old from public.market_listings where id = p_id;
  if v_old.id is null then raise exception 'not_found' using errcode = 'P0002'; end if;
  delete from public.market_listings where id = p_id;
  perform public._admin_log('market.delete', 'market_listing', p_id::text,
    jsonb_build_object('listing_no', v_old.listing_no, 'brand', v_old.brand, 'model', v_old.model, 'owner_id', v_old.owner_id),
    jsonb_build_object('reason', p_reason));
end;
$$;

