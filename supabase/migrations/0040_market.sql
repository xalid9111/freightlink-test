-- ---------------------------------------------------------------------
-- Reports: + 'market_listing' (every value already allowed stays).
-- ---------------------------------------------------------------------
do $$
declare v_allowed text[]; v_have text;
begin
  select coalesce(array_agg(distinct x order by x), '{}') into v_allowed from (
    select unnest(array['cargo','user','message','offer','shipment','service','other','market_listing']) x
    union
    select r.target_type from public.reports r where r.target_type is not null
    union
    select m[1] from pg_constraint c,
      regexp_matches(pg_get_constraintdef(c.oid), '''([a-z_]+)''', 'g') m
    where c.conrelid = 'public.reports'::regclass and c.conname = 'reports_target_type_check'
  ) s;
  select pg_get_constraintdef(c.oid) into v_have from pg_constraint c
   where c.conrelid = 'public.reports'::regclass and c.conname = 'reports_target_type_check';
  if v_have is null or v_have not like '%''market_listing''%' then
    if v_have is not null then alter table public.reports drop constraint reports_target_type_check; end if;
    execute format('alter table public.reports add constraint reports_target_type_check check (target_type = any (array[%s]))',
      (select string_agg(quote_literal(x), ', ') from unnest(v_allowed) x));
  end if;
end $$;

