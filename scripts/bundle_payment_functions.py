#!/usr/bin/env python3
"""Build single-file copies of the payment Edge Functions for pasting into
the Supabase Dashboard editor (Edge Functions -> Deploy a new function ->
Via Editor), which is easier than the CLI when a function imports
../_shared/.

  python3 scripts/bundle_payment_functions.py          # write the bundles
  python3 scripts/bundle_payment_functions.py --check  # fail if they are stale

Source of truth: supabase/functions/{payments-checkout,payments-webhook}/index.ts
and supabase/functions/_shared/payments.ts. Never edit the bundles by hand.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "supabase/functions/_shared/payments.ts"
OUT = ROOT / "docs/payments"
FUNCS = ["payments-checkout", "payments-webhook"]
IMPORT = re.compile(r"^import \{[^}]*\} from '\.\./_shared/payments\.ts';\n", re.M)


def bundle(name: str) -> str:
    src = (ROOT / f"supabase/functions/{name}/index.ts").read_text()
    if len(IMPORT.findall(src)) != 1:
        sys.exit(f"{name}: expected exactly one ../_shared/payments.ts import")
    head = (f"// GENERATED by scripts/bundle_payment_functions.py — do not edit.\n"
            f"// Single-file copy of supabase/functions/{name}/index.ts with\n"
            f"// supabase/functions/_shared/payments.ts inlined, for the Supabase\n"
            f"// Dashboard editor. Paste the whole file as the function's index.ts.\n\n")
    inlined = "// ---- inlined: _shared/payments.ts ----\n" + SHARED.read_text() + "// ---- end of inlined file ----\n\n"
    return head + IMPORT.sub(lambda _m: inlined, src)


def main() -> None:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name in FUNCS:
        path = OUT / f"{name}.dashboard.ts"
        text = bundle(name)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
            print("wrote", path.relative_to(ROOT))
    if stale:
        sys.exit("stale bundles (run scripts/bundle_payment_functions.py): " + ", ".join(stale))
    if check:
        print("Payment dashboard bundles are up to date.")


if __name__ == "__main__":
    main()
